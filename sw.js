/* Cross-origin assets cached best-effort. ONLY hosts without their own SW belong
   here — Dexie (unpkg) and Google Fonts. Cache-first so the app still boots
   offline. */
const RUNTIME_HOSTS = new Set([
  'unpkg.com',
  'fonts.googleapis.com',
  'fonts.gstatic.com',
]);

/* ---------- Validator helpers ---------- */

function validatorOf(res) {
  if (!res || !res.ok) return null;
  return res.headers.get('ETag') || res.headers.get('Last-Modified') || null;
}

async function headValidator(url) {
  try {
    const res = await fetch(url, { method: 'HEAD', cache: 'no-store' });
    return validatorOf(res);
  } catch {
    return null;
  }
}

/* ---------- Cache open helpers ---------- */

async function openCache(name) {
  return caches.open(name);
}

async function readMeta(key) {
  const cache = await openCache(META_CACHE);
  const res = await cache.match(key);
  if (!res) return null;
  try {
    return await res.text();
  } catch {
    return null;
  }
}

async function writeMeta(key, value) {
  const cache = await openCache(META_CACHE);
  await cache.put(key, new Response(value));
}

/* ---------- Install: precache the shell ---------- */

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await openCache(SHELL_CACHE);
      await Promise.all(
        SHELL_ASSETS.map(async (url) => {
          try {
            await cache.add(new Request(url, { cache: 'reload' }));
          } catch {
            /* best-effort: a missing asset shouldn't break install */
          }
        })
      );
      await self.skipWaiting();
    })()
  );
});

/* ---------- Activate: clean old caches ---------- */

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((k) => k !== SHELL_CACHE && k !== RUNTIME_CACHE && k !== META_CACHE)
          .map((k) => caches.delete(k))
      );
      await self.clients.claim();
    })()
  );
});

/* ---------- Sentinel check (throttled) ---------- */

// Detect a new deploy but DO NOT apply it. Store the pending sentinel and
// notify clients. Nothing is refetched until a client sends
// 'labtestbook-apply-update' (the user accepting the prompt). This guarantees
// that a plain reload never silently picks up the new version.
async function checkForUpdate() {
  const last = Number(await readMeta(LAST_CHECK_KEY)) || 0;
  if (Date.now() - last < CHECK_GUARD_MS) return;
  await writeMeta(LAST_CHECK_KEY, String(Date.now()));

  const current = await headValidator(SENTINEL_URL);
  if (!current) return;
  const stored = await readMeta(SENTINEL_KEY);
  if (stored === current) {
    // Nothing new. Clear any stale pending marker.
    await writeMeta(PENDING_KEY, '');
    return;
  }

  // New deploy detected — mark pending, notify, but do not touch the cache.
  await writeMeta(PENDING_KEY, current);
  const clients = await self.clients.matchAll({ type: 'window' });
  for (const client of clients) {
    client.postMessage({ type: 'labtestbook-update-available' });
  }
}

// Apply the pending update (user accepted). Refetches only the shell assets
// whose validators changed, then records the new sentinel and tells clients to
// reload. Idempotent: a second apply with no pending sentinel is a no-op.
async function applyUpdate() {
  const pending = await readMeta(PENDING_KEY);
  if (!pending) return false;

  const cache = await openCache(SHELL_CACHE);
  await Promise.all(
    SHELL_ASSETS.map(async (url) => {
      try {
        const val = await headValidator(url);
        if (!val) return;
        const key = ASSET_VAL_PREFIX + url;
        const prev = await readMeta(key);
        if (prev === val) return;
        await writeMeta(key, val);
        await cache.add(new Request(url, { cache: 'reload' }));
      } catch {
        /* best-effort */
      }
    })
  );

  await writeMeta(SENTINEL_KEY, pending);
  await writeMeta(PENDING_KEY, '');
  const clients = await self.clients.matchAll({ type: 'window' });
  for (const client of clients) {
    client.postMessage({ type: 'labtestbook-update-applied' });
  }
  return true;
}

/* ---------- Fetch: shell cache-first, runtime cache-first, network passthrough ---------- */

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Sentinel — always network (must see the fresh validator).
  if (url.pathname.endsWith('/version.txt')) return;

  // Same-origin shell asset -> shell cache first.
  if (url.origin === self.location.origin) {
    event.respondWith(
      (async () => {
        const cache = await openCache(SHELL_CACHE);
        const hit = await cache.match(req, { ignoreSearch: false });
        if (hit) {
          // Background sentinel check piggybacks on any same-origin GET.
          event.waitUntil(checkForUpdate());
          return hit;
        }
        try {
          const res = await fetch(req);
          if (res && res.ok) cache.put(req, res.clone()).catch(() => { });
          return res;
        } catch {
          const fallback = await cache.match('./index.html');
          if (fallback) return fallback;
          return new Response('Offline', { status: 503 });
        }
      })()
    );
    return;
  }

  // Cross-origin runtime asset on a known host -> runtime cache first.
  if (RUNTIME_HOSTS.has(url.hostname)) {
    event.respondWith(
      (async () => {
        const cache = await openCache(RUNTIME_CACHE);
        const hit = await cache.match(req, { ignoreSearch: false });
        if (hit) return hit;
        try {
          const res = await fetch(req);
          if (res && res.ok) cache.put(req, res.clone()).catch(() => { });
          return res;
        } catch {
          return new Response('', { status: 504 });
        }
      })()
    );
    return;
  }

  // Everything else passes through.
});

/* ---------- Message: manual update check ---------- */

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'labtestbook-check-update') {
    event.waitUntil(checkForUpdate());
  } else if (event.data && event.data.type === 'labtestbook-apply-update') {
    event.waitUntil(applyUpdate());
  }
});
